def alpha_rise(t_rel: np.ndarray, tau: float, peak: float) -> np.ndarray:
    """alpha 函数上升相."""
    sig = np.zeros_like(t_rel)
    mask = (t_rel >= 0) & (t_rel <= tau)
    x = t_rel[mask] / tau
    sig[mask] = peak * x * np.exp(1.0 - x)
    return sig


def generate_release_profile(t: np.ndarray, stim_time: float,
                              duration: float, peak: float,
                              rise_tau: float, stim_type: str,
                              v_max: float = 0.0, k_m: float = 0.0) -> np.ndarray:
    """生成单次刺激的释放速率剖面."""
    t_rel = t - stim_time
    release = np.zeros_like(t)

    if stim_type == "pulse":
        mask = (t_rel >= 0) & (t_rel <= rise_tau)
        x = t_rel[mask] / rise_tau
        release[mask] = (peak / rise_tau) * x * np.exp(1.0 - x)
    elif stim_type in ("plateau", "ramp"):
        if v_max > 0 and k_m > 0:
            release_rate = v_max * peak / (k_m + peak)
        else:
            release_rate = peak * 2.0
        rise_end = duration / 3.0
        plateau_end = 2.0 * duration / 3.0
        rise = (t_rel >= 0) & (t_rel <= rise_end)
        release[rise] = release_rate * (t_rel[rise] / rise_end)
        plateau = (t_rel > rise_end) & (t_rel <= plateau_end)
        release[plateau] = release_rate
        fall = (t_rel > plateau_end) & (t_rel <= duration)
        release[fall] = release_rate * (1.0 - (t_rel[fall] - plateau_end) / rise_end)
    return release


def poisson_stim_times(rate: float, duration: float, rng: np.random.Generator,
                        min_gap: float = 2.0) -> list[float]:
    """非齐次泊松过程生成刺激时间."""
    times = []
    t = 0.0
    while t < duration:
        gap = rng.exponential(1.0 / rate) if rate > 0 else duration
        t += gap
        if t >= duration:
            break
        if not times or (t - times[-1]) >= min_gap:
            times.append(t)
    return times


def simulate_concentration(release: np.ndarray, v_max: float, k_m: float,
                             dt: float, c_init: float = 0.0) -> np.ndarray:
    """Michaelis-Menten 数值积分."""
    n = len(release)
    conc = np.zeros(n, dtype=np.float64)
    conc[0] = c_init
    for i in range(1, n):
        uptake = v_max * conc[i-1] / (k_m + conc[i-1])
        conc[i] = conc[i-1] + (release[i] - uptake) * dt
        if conc[i] < 0:
            conc[i] = 0.0
    return conc


