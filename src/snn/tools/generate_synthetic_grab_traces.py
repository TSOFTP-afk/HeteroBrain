def get_category_map(config: dict) -> dict:
    """从 YAML 的 categories 字段动态构建分类映射 (支持新增类别)."""
    return config.get("categories", {})


def filter_enabled_presets(preset_names: list, config: dict,
                            include_disabled: bool) -> tuple[list, list]:
    """根据 enabled 标志过滤场景.

    返回: (启用场景列表, 跳过的禁用场景列表)
    病理类场景默认 enabled: false, 需 --include-disabled 显式启用.
    """
    enabled, skipped = [], []
    for name in preset_names:
        scene = config["presets"].get(name, {})
        is_enabled = scene.get("enabled", True)
        if is_enabled or include_disabled:
            enabled.append(name)
        else:
            skipped.append(name)
    return enabled, skipped


def main() -> int:
    parser = argparse.ArgumentParser(
        description="生成合成神经调质轨迹数据集 v4 (多场景, 4 维细化, 病理类开关)."
    )
    parser.add_argument(
        "--preset", default="all",
        help="场景预设: all | 类别名(奖赏类/应激类/...) | 具体场景名 (逗号分隔)",
    )
    parser.add_argument(
        "--intensity", default="0",
        help="强度梯度 (-50 到 +50 整数): all | N | N1,N2,N3 | START:END[:STEP] (默认 0)",
    )
    parser.add_argument(
        "--config", default="src/snn/tools/traces_config.yaml",
        help="YAML 配置文件路径",
    )
    parser.add_argument(
        "--output-dir", default="data/neuroscience_traces/datasets",
        help="数据集输出根目录",
    )
    parser.add_argument("--duration", type=float, default=None, help="覆盖配置中的轨迹时长 (秒)")
    parser.add_argument("--fs", type=float, default=None, help="覆盖配置中的采样率 (Hz)")
    parser.add_argument("--seed", type=int, default=42, help="随机种子 (默认 42)")
    parser.add_argument("--list-presets", action="store_true", help="列出所有可用场景预设")
    parser.add_argument(
        "--include-disabled", action="store_true",
        help="强制启用被标记为 enabled:false 的场景 (默认跳过病理类)",
    )
    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"[ERROR] 配置文件不存在: {config_path}", file=sys.stderr)
        return 1
    config = load_config(config_path)

    if args.duration is not None:
        config["global"]["duration_s"] = args.duration
    if args.fs is not None:
        config["global"]["fs_hz"] = args.fs

    categories = get_category_map(config)

    if args.list_presets:
        total = len(config["presets"])
        n_enabled = sum(1 for s in config["presets"].values()
                        if s.get("enabled", True))
        n_disabled = total - n_enabled
        print(f"可用场景预设 (共 {total} 个, 启用 {n_enabled}, 禁用 {n_disabled}):")
        for cat, names in categories.items():
            print(f"\n  [{cat}] ({len(names)} 个)")
            for name in names:
                scene = config["presets"].get(name, {})
                desc = scene.get("description", "")[:50]
                flag = "" if scene.get("enabled", True) else " [DISABLED]"
                print(f"    {name:35s} - {desc}{flag}")
        print("\n强度梯度: -50 到 +50 整数 (scale = 1 + 0.02*i)")
        print("  示例: --intensity 0 | -10,0,10 | -10:10 | -50:50:5 | all")
        print("  兼容: weak(-25) | medium(0) | strong(25)")
        print("提示: 禁用场景需 --include-disabled 才生成")
        return 0

    # 解析预设
    if args.preset.lower() == "all":
        preset_names = list(config["presets"].keys())
    elif args.preset in categories:
        preset_names = categories[args.preset]
    else:
        preset_names = [p.strip() for p in args.preset.split(",")]
        for name in preset_names:
            if name not in config["presets"]:
                print(f"[ERROR] 未知预设: {name}", file=sys.stderr)
                print(f"        可用: {', '.join(config['presets'].keys())}", file=sys.stderr)
                return 1

    # 根据 enabled 标志过滤
    preset_names, skipped = filter_enabled_presets(
        preset_names, config, args.include_disabled)

    if skipped and not args.include_disabled:
        print(f"[INFO] 跳过 {len(skipped)} 个禁用场景 (病理类, 使用 --include-disabled 启用):")
        for name in skipped:
            print(f"       - {name}")

    if not preset_names:
        print("[WARN] 没有启用的场景可生成. 使用 --include-disabled 启用病理类场景.")
        return 0

    # 解析强度 (-50 到 +50 整数)
    intensities = parse_intensity_arg(args.intensity)
    if intensities is None:
        print(f"[ERROR] 无效的强度参数: {args.intensity}", file=sys.stderr)
        print("       支持格式: all | N | N1,N2,N3 | START:END | START:END:STEP", file=sys.stderr)
        print("       范围: -50 到 +50", file=sys.stderr)
        return 1

    output_root = Path(args.output_dir)
    output_root.mkdir(parents=True, exist_ok=True)

    print(f"[INFO] 生成神经调质轨迹数据集 v{DATASET_VERSION}")
    print(f"       输出: {output_root}")
    print(f"       启用场景: {len(preset_names)}, 跳过: {len(skipped)}, 强度档: {len(intensities)}")
    print(f"       总子数据集: {len(preset_names) * len(intensities)}")
    print(f"       时长: {config['global']['duration_s']}s, "
          f"采样率: {config['global']['fs_hz']}Hz, 种子: {args.seed}")

    snapshot_path = save_config_snapshot(config, output_root)
    print(f"\n[OK] 配置快照: {snapshot_path}")

    # 生成所有场景 × 强度
    scenarios_meta = []
    start_time = time.time()
    for name in preset_names:
        for intensity in intensities:
            meta = generate_scenario(
                name, config["presets"][name], config,
                output_root, args.seed, intensity)
            scenarios_meta.append(meta)

    elapsed = time.time() - start_time
    manifest_path = generate_manifest(output_root, config, scenarios_meta, config_path, args)

    print(f"\n[OK] Manifest: {manifest_path}")
    print(f"\n{'='*70}")
    print(f"[DONE] 数据集生成完成")
    print(f"       启用场景: {len(preset_names)}")
    print(f"       强度档: {len(intensities)}")
    print(f"       总子数据集: {len(scenarios_meta)}")
    print(f"       总事件数: {sum(s['n_events'] for s in scenarios_meta)}")
    print(f"       耗时: {elapsed:.2f}s")
    print(f"       配置 SHA256: {compute_config_hash(config)[:16]}...")
    print(f"       可复现: 相同配置 + seed={args.seed} → 完全相同数据集")
    print(f"{'='*70}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
