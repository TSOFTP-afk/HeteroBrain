def get_brain_region_params(channel: str, brain_region: str,
                              base_params: dict, brain_regions: dict) -> dict:
    """合并基础参数 + 脑区特异性参数."""
    params = dict(base_params.get(channel, {}))
    region_params = brain_regions.get(brain_region, {}).get(channel, {})
    params.update(region_params)
    return params


def apply_intensity(params: dict, intensity,
                     intensity_levels: dict) -> dict:
    """应用强度梯度缩放.

    支持 -50 到 +50 的整数强度 (线性映射):
        scale = max(0.05, 1.0 + intensity * 0.02)
    兼容旧版 weak/medium/strong 字符串 (自动转换为 -25/0/+25).
    """
    # 兼容旧版字符串命名
    if isinstance(intensity, str):
        legacy_map = {"weak": -25, "medium": 0, "strong": 25}
        if intensity in legacy_map:
            intensity = legacy_map[intensity]
        else:
            # 尝试解析为整数
            try:
                intensity = int(intensity)
            except (ValueError, TypeError):
                intensity = 0

    # 线性映射: scale = max(0.05, 1.0 + intensity * 0.02)
    scale = max(0.05, 1.0 + intensity * 0.02)

    if intensity == 0:
        return params  # 基准无缩放

    result = dict(params)
    if "peak_df" in result:
        lo, hi = result["peak_df"]
        result["peak_df"] = [lo * scale, hi * scale]
    if "poisson_rate" in result:
        result["poisson_rate"] = result["poisson_rate"] * scale
    return result


def parse_intensity_arg(arg: str) -> list[int] | None:
    """解析强度命令行参数.

    支持格式:
        "all"              → -50 到 +50 全部 101 档
        "0"                → [0]
        "-10,0,10"         → [-10, 0, 10]
        "-10:10"           → [-10, -9, ..., 10] (步长 1)
        "-50:50:5"         → [-50, -45, ..., 50] (步长 5)
        "weak"             → [-25] (兼容旧版)
        "medium"           → [0] (兼容旧版)
        "strong"           → [25] (兼容旧版)

    返回: 整数列表, 或 None 表示解析失败.
    """
    arg = arg.strip()
    if not arg:
        return None

    # 兼容旧版命名
    legacy_map = {"weak": [-25], "medium": [0], "strong": [25]}
    if arg.lower() in legacy_map:
        return legacy_map[arg.lower()]

    # all: -50 到 +50 全部
    if arg.lower() == "all":
        return list(range(-50, 51))

    # 逗号分隔列表: -10,0,10
    if "," in arg:
        result = []
        for part in arg.split(","):
            part = part.strip()
            try:
                v = int(part)
                if not -50 <= v <= 50:
                    return None
                result.append(v)
            except ValueError:
                return None
        return result if result else None

    # 范围: START:END[:STEP]
    if ":" in arg:
        parts = arg.split(":")
        if len(parts) < 2 or len(parts) > 3:
            return None
        try:
            start = int(parts[0])
            end = int(parts[1])
            step = int(parts[2]) if len(parts) == 3 else 1
        except ValueError:
            return None
        if step <= 0:
            return None
        # 钳位到 [-50, 50]
        start = max(-50, min(50, start))
        end = max(-50, min(50, end))
        if start <= end:
            return list(range(start, end + 1, step))
        else:
            return list(range(start, end - 1, -step))

    # 单个整数
    try:
        v = int(arg)
        if not -50 <= v <= 50:
            return None
        return [v]
    except ValueError:
        return None


