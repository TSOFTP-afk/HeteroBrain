# 场景生成 (含阶段/脑区/强度/行为标注)
# ============================================================================
def generate_scenario(scenario_name: str, scenario_config: dict,
                       config: dict, output_root: Path, seed: int,
                       intensity = 0) -> dict:
    """生成单个场景的完整数据 (CSV + NPZ + events.json).

    支持 4 维细化:
    - 时间阶段: 刺激只在指定 phase 内出现
    - 脑区: 使用对应脑区的时间常数和摄取参数
    - 强度: -50..+50 整数 (线性映射 scale=1+0.02*i), 兼容 weak/medium/strong
    - 行为: 在 events.json 中输出 behavior 标注
    """
    global_config = config["global"]
    base_params = config["base_params"]
    brain_regions = config["brain_regions"]
    intensity_levels = config["intensity_levels"]
    phase_template = get_phase_template(scenario_config, config)

    duration = global_config["duration_s"]
    fs = global_config["fs_hz"]
    noise_scale = global_config.get("noise_std_scale", 1.0)
    da_5ht_coupling = global_config.get("da_5ht_coupling", 0.3)

    n_samples = int(duration * fs)
    t = np.linspace(0, duration, n_samples, dtype=np.float64)
    dt = float(t[1] - t[0])

    # 兼容旧版字符串强度 (weak/medium/strong → -25/0/+25)
    if isinstance(intensity, str):
        legacy_map = {"weak": -25, "medium": 0, "strong": 25}
        intensity = legacy_map.get(intensity, 0)

    # 强度归一化到整数 (支持浮点输入如 -25.5)
    intensity = int(round(intensity))

    # 场景种子 (场景名+强度联合哈希, 保证可复现且各版本独立)
    # 强度偏移: (intensity + 50) * 1000, 范围 [0, 100000], 保证非负且唯一
    #   intensity=-50 → offset=0, intensity=0 → offset=50000, intensity=+50 → offset=100000
    intensity_offset = (intensity + 50) * 1000
    scenario_seed = seed + hash(scenario_name) % 100000 + intensity_offset
    rng = np.random.default_rng(scenario_seed)

    # 输出目录: datasets/{scenario}/i{intensity:+03d}/
    # 命名: i-50, i-05, i+00, i+25, i+50 (补零对齐, 保证字典序)
    intensity_str = f"i{intensity:+03d}"
    scenario_dir = output_root / scenario_name / intensity_str
    csv_dir = scenario_dir / "csv"
    csv_dir.mkdir(parents=True, exist_ok=True)

    # 计算实际缩放因子 (用于日志和元数据)
    scale = max(0.05, 1.0 + intensity * 0.02)

    brain_region = scenario_config.get("brain_region", "PFC")
    behavior = scenario_config.get("behavior", "unknown")
    paradigm = scenario_config.get("paradigm", "unknown")

    print(f"\n[{scenario_name}/{intensity_str}] scale={scale:.2f} {scenario_config.get('description', '')[:40]}...")
    print(f"       brain={brain_region}, behavior={behavior}, seed={scenario_seed}")

    # 合并调质参数 (基础 + 脑区 + 场景覆盖 + 强度)
    modulators_config = scenario_config["modulators"]
    merged_params = {}
    for ch in CHANNELS:
        if ch not in modulators_config:
            continue
        base = get_brain_region_params(ch, brain_region, base_params, brain_regions)
        scene_override = modulators_config[ch]
        merged = {**base, **scene_override}
        merged = apply_intensity(merged, intensity, intensity_levels)
        merged_params[ch] = merged

    # 收集事件
    all_events = []
    concentrations = {}

    # 先生成 DA (用于 5HT 拮抗耦合)
    if "DA" in merged_params:
        da_sig, da_events = _generate_channel_with_phases(
            "DA", merged_params["DA"], t, rng, da_5ht_coupling,
            None, noise_scale, phase_template)
        concentrations["DA"] = da_sig.astype(np.float64)
        _save_csv(csv_dir / "DA.csv", t, da_sig)
        all_events.extend(da_events)

    # 生成 5HT (受 DA 拮抗)
    if "5HT" in merged_params:
        ht5_sig, ht5_events = _generate_channel_with_phases(
            "5HT", merged_params["5HT"], t, rng, da_5ht_coupling,
            concentrations.get("DA"), noise_scale, phase_template)
        concentrations["5HT"] = ht5_sig.astype(np.float64)
        _save_csv(csv_dir / "5HT.csv", t, ht5_sig)
        all_events.extend(ht5_events)

    # 生成 NE, ACh, Oxy
    for ch in ["NE", "ACh", "Oxy"]:
        if ch not in merged_params:
            continue
        sig, events = _generate_channel_with_phases(
            ch, merged_params[ch], t, rng, da_5ht_coupling,
            None, noise_scale, phase_template)
        concentrations[ch] = sig.astype(np.float64)
        _save_csv(csv_dir / f"{ch}.csv", t, sig)
        all_events.extend(events)

    # 保存 NPZ
    npz_path = scenario_dir / "traces.npz"
    np.savez_compressed(
        npz_path,
        time_s=t.astype(np.float32),
        **{ch: conc.astype(np.float32) for ch, conc in concentrations.items()},
        fs_hz=np.float32(fs),
        duration_s=np.float32(duration),
    )

    # 保存 events.json (含行为标注和阶段信息)
    events_data = {
        "scenario": scenario_name,
        "intensity": intensity,
        "intensity_str": intensity_str,
        "intensity_scale": float(scale),
        "description": scenario_config.get("description", ""),
        "paradigm": paradigm,
        "behavior": behavior,
        "brain_region": brain_region,
        "expected_state": scenario_config.get("expected_state", {}),
        "phases": phase_template,
        "n_events": len(all_events),
        "events": all_events,
    }
    events_path = scenario_dir / "events.json"
    with events_path.open("w", encoding="utf-8") as f:
        json.dump(events_data, f, indent=2, ensure_ascii=False)

    # 统计
    stats = {}
    for ch, conc in concentrations.items():
        stats[ch] = {
            "min": float(conc.min()),
            "max": float(conc.max()),
            "mean": float(conc.mean()),
        }

    for ch in CHANNELS:
        if ch in stats:
            s = stats[ch]
            n_ev = sum(1 for e in all_events if e["channel"] == ch)
            print(f"       {ch:4s}: min={s['min']:.3f} max={s['max']:.3f} "
                  f"mean={s['mean']:.3f} events={n_ev}")

    return {
        "scenario": scenario_name,
        "intensity": intensity,
        "intensity_str": intensity_str,
        "intensity_scale": float(scale),
        "description": scenario_config.get("description", ""),
        "paradigm": paradigm,
        "behavior": behavior,
        "brain_region": brain_region,
        "expected_state": scenario_config.get("expected_state", {}),
        "seed": scenario_seed,
        "n_events": len(all_events),
        "stats": stats,
        "files": {
            "csv_dir": str(csv_dir.relative_to(output_root.parent)),
            "traces_npz": str(npz_path.relative_to(output_root.parent)),
            "events_json": str(events_path.relative_to(output_root.parent)),
        },
    }


def _generate_channel_with_phases(channel: str, params: dict, t: np.ndarray,
                                    rng: np.random.Generator, da_5ht_coupling: float,
                                    da_conc: np.ndarray | None, noise_scale: float,
                                    phase_template: dict) -> tuple[np.ndarray, list]:
    """生成单通道轨迹, 刺激只在指定 phase 时间窗口内出现."""
    duration = float(t[-1])
    dt = float(t[1] - t[0]) if len(t) > 1 else 0.01

    # 获取该调质的目标 phase
    target_phase = params.get("phase", "CS")
    phase_info = phase_template.get(target_phase, {})
    phase_start = phase_info.get("start", 0)
    phase_duration = phase_info.get("duration", duration)
    phase_end = min(phase_start + phase_duration, duration)

    # 泊松过程生成刺激时间 (限制在 phase 时间窗口内)
    rate = params.get("poisson_rate", 0.05)
    stim_duration = params.get("stim_duration", 1.0)
    stim_times = poisson_stim_times(rate, phase_duration - stim_duration, rng,
                                      min_gap=stim_duration * 2.0)
    # 平移到 phase 起始时间
    stim_times = [st + phase_start for st in stim_times]
    if len(stim_times) < 2:
        n_fallback = max(3, int(phase_duration * rate))
        stim_times = list(np.linspace(phase_start + 0.1 * phase_duration,
                                        phase_end - 0.1 * phase_duration, n_fallback))

    # 累加释放速率
    total_release = np.zeros_like(t)
    events = []
    peak_lo, peak_hi = params.get("peak_df", [0.2, 0.4])

    # 路径 D: 对数正态峰值分布 (真实 DA 瞬态峰值呈右偏分布, Phillips 2003)
    # 将 [peak_lo, peak_hi] 转换为对数正态参数:
    #   均值 = (lo+hi)/2, 中位数略低于均值 (右偏)
    peak_mean = (peak_lo + peak_hi) * 0.5
    peak_std = (peak_hi - peak_lo) * 0.25  # 约 1/4 范围作为标准差
    # 防止 peak_mean <= 0 (低强度场景)
    if peak_mean <= 0.01:
        peak_mean = max(peak_mean, 0.02)
        peak_std = max(peak_std, 0.005)
    # 对数正态参数: mu = ln(mean^2 / sqrt(mean^2 + std^2))
    #                sigma = sqrt(ln(1 + std^2/mean^2))
    var_plus_mean2 = peak_mean * peak_mean + peak_std * peak_std
    log_mu = np.log(peak_mean * peak_mean / np.sqrt(var_plus_mean2))
    log_sigma = np.sqrt(np.log(var_plus_mean2 / (peak_mean * peak_mean)))

    for stim_t in stim_times:
        # 对数正态采样, 钳位到 [peak_lo*0.3, peak_hi*1.5] 防极端值
        peak = float(rng.lognormal(log_mu, log_sigma))
        peak = max(peak_lo * 0.3, min(peak_hi * 1.5, peak))

        # DA-5HT 拮抗耦合
        coupling_applied = 0.0
        if channel == "5HT" and da_conc is not None:
            stim_idx = min(int(np.searchsorted(t, stim_t)), len(da_conc) - 1)
            da_at_stim = da_conc[stim_idx]
            inhibition = da_5ht_coupling * min(da_at_stim, 1.0)
            coupling_applied = inhibition
            peak = peak * (1.0 - inhibition)

        rel = generate_release_profile(
            t, stim_t, stim_duration, peak,
            params["rise_tau"], params["stim_type"],
            params.get("v_max", 1.0), params.get("k_m", 0.3))
        total_release += rel

        events.append({
            "channel": channel,
            "time_s": float(stim_t),
            "peak_target": float(peak),
            "stim_type": params["stim_type"],
            "stim_duration_s": float(stim_duration),
            "phase": target_phase,
            "da_5ht_coupling_applied": float(coupling_applied),
            "peak_distribution": "lognormal",
        })

    # Michaelis-Menten 积分
    conc = simulate_concentration(total_release,
                                    params.get("v_max", 1.0),
                                    params.get("k_m", 0.3), dt)

    # 路径 C: 1/f 闪烁噪声 + 慢漂移 (替代高斯白噪声)
    # 真实 GRAB 信号噪声谱: 1/f (低频强, 高频弱) + 慢漂移 (< 0.1Hz)
    # 来源: GRAB 探针光漂白 + 血流信号 + 呼吸节律
    noise_std = params["noise_std"] * noise_scale
    noise = _generate_realistic_noise(len(t), noise_std, rng)

    # 基线 + 真实噪声
    df_f = conc.astype(np.float32)
    df_f += params.get("baseline", 0.0)
    df_f += noise.astype(np.float32)
    df_f = np.clip(df_f, 0.0, 1.5)

    return df_f, events


def _generate_realistic_noise(n: int, sigma: float,
                                rng: np.random.Generator) -> np.ndarray:
    """生成 1/f 闪烁噪声 + 慢漂移 + 高频白噪声 (模拟真实 GRAB 信号).

    真实 GRAB 探针信号的噪声组成:
      1. 1/f 闪烁噪声 (光漂白 + 探测器噪声, 低频强)
      2. 慢漂移 (血流/呼吸节律, < 0.1 Hz)
      3. 高频白噪声 (读出噪声)

    实现: 频域 1/f 滤波 + 正弦慢漂移叠加.
    """
    if n < 4 or sigma <= 0:
        return np.zeros(n, dtype=np.float32)

    # 1. 1/f 闪烁噪声: 频域生成
    # 白噪声 → FFT → 乘 1/sqrt(f) → IFFT
    white = rng.standard_normal(n).astype(np.float64)
    fft = np.fft.rfft(white)
    freqs = np.fft.rfftfreq(n)
    # 避免除零, freqs[0]=0 时保持原值 (DC 分量)
    freqs[0] = 1.0
    # 1/f 滤波: 振幅 ∝ 1/sqrt(f)
    spectrum = fft / np.sqrt(np.abs(freqs))
    # 恢复 DC 分量为 0 (避免常数偏移)
    spectrum[0] = 0.0
    flicker = np.fft.irfft(spectrum, n=n)
    # 归一化到目标标准差
    flicker_std = flicker.std()
    if flicker_std > 1e-10:
        flicker = flicker / flicker_std * sigma * 0.6  # 60% 来自 1/f

    # 2. 慢漂移: 0.02-0.1 Hz 正弦混合 (模拟呼吸 + 血流)
    t_idx = np.arange(n, dtype=np.float64)
    drift_freqs = rng.uniform(0.02, 0.10, size=2)  # 2 个随机低频
    drift_phases = rng.uniform(0, 2 * np.pi, size=2)
    drift = np.zeros(n, dtype=np.float64)
    for f, p in zip(drift_freqs, drift_phases):
        drift += np.sin(2 * np.pi * f * t_idx / n + p)
    # 漂移幅度: sigma * 0.3 (30% 来自慢漂移)
    drift = drift / drift.std() * sigma * 0.3 if drift.std() > 1e-10 else drift

    # 3. 高频白噪声: 10% (少量读出噪声)
    white_high = rng.standard_normal(n).astype(np.float64) * sigma * 0.1

    noise = flicker + drift + white_high
    return noise


def _save_csv(path: Path, time_s: np.ndarray, df_f: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["time_s", "dF_F"])
        for t_val, v in zip(time_s, df_f):
            writer.writerow([f"{t_val:.4f}", f"{v:.6f}"])


